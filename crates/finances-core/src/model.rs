/// Generate a cuid-like id: `c` + unix-millis hex + 10 random bytes hex.
pub fn new_id() -> String {
    let millis = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0);
    let mut bytes = [0u8; 10];
    getrandom::fill(&mut bytes).expect("system entropy unavailable");
    let mut s = String::with_capacity(25);
    s.push('c');
    s.push_str(&format!("{millis:012x}"));
    for b in bytes {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

/// Current UTC timestamp in the same shape as the web app (`ISO-ish` string).
#[must_use]
pub fn now_iso() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let (y, m, d, hh, mm, ss) = civil_from_unix(secs as i64);
    format!("{y:04}-{m:02}-{d:02}T{hh:02}:{mm:02}:{ss:02}Z")
}

/// Days since 1970-01-01 for a civil date (Howard Hinnant's algorithm).
#[must_use]
pub fn days_from_civil(y: i64, m: u32, d: u32) -> i64 {
    let y = i64::from(y) - if m <= 2 { 1 } else { 0 };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let mp = (i64::from(m) + 9) % 12;
    let doy = (153 * mp + 2) / 5 + i64::from(d) - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// Inverse of [`days_from_civil`] + seconds-of-day.
#[must_use]
pub fn civil_from_unix(secs: i64) -> (i64, u32, u32, u32, u32, u32) {
    let days = secs.div_euclid(86_400);
    let sod = secs.rem_euclid(86_400);
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    (
        y,
        m as u32,
        d as u32,
        (sod / 3600) as u32,
        ((sod % 3600) / 60) as u32,
        (sod % 60) as u32,
    )
}

/// Today's UTC date as `YYYY-MM-DD`.
#[must_use]
pub fn today_iso() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    let (y, m, d, _, _, _) = civil_from_unix(secs);
    format!("{y:04}-{m:02}-{d:02}")
}

/// Current month key `YYYY-MM` (UTC) — mirrors `currentMonthKey` in TS
/// (which uses local time; the desktop app standardizes on UTC).
#[must_use]
pub fn current_month_key() -> String {
    today_iso()[..7].to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn id_shape_and_uniqueness() {
        let a = new_id();
        let b = new_id();
        assert!(a.starts_with('c'));
        assert_eq!(a.len(), 33); // 'c' + 12 hex millis + 20 hex random
        assert_ne!(a, b);
        assert!(crate::validation::parse_id(&a).is_ok());
    }

    #[test]
    fn civil_round_trip() {
        let (y, m, d, _, _, _) = civil_from_unix(0);
        assert_eq!((y, m, d), (1970, 1, 1));
        let (y, m, d, _, _, _) = civil_from_unix(1_700_000_000); // 2023-11-14
        assert_eq!((y, m, d), (2023, 11, 14));
        assert_eq!(days_from_civil(2026, 11, 13), days_from_civil(2026, 11, 13));
        // Inverse property
        for secs in [0i64, 86_399, 1_762_000_000, 4_102_444_800] {
            let (y, m, d, _, _, _) = civil_from_unix(secs);
            assert_eq!(days_from_civil(y, m, d), secs.div_euclid(86_400));
        }
    }
}
