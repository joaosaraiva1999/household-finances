//! Domain records. Money is integer cents; enums are closed sets.
//! All structs serialize in camelCase so the Tauri IPC layer (and the future
//! frontend wiring) can consume them exactly like the web API payloads.

use crate::validation::{Kind, Person, Responsible};

#[derive(Debug, Clone, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Expense {
    pub id: String,
    pub name: String,
    pub amount_cents: i64,
    pub kind: Kind,
    pub category: String,
    pub responsible: Responsible,
    /// Percentage paid by João (0–100) for shared entries; display value.
    pub joao_share: f64,
    /// Exact amounts paid per person for shared money-out entries.
    pub joao_paid_cents: Option<i64>,
    pub anna_paid_cents: Option<i64>,
    /// `YYYY-MM-DD` or `None`.
    pub due_date: Option<String>,
    pub paid: bool,
    pub notes: Option<String>,
    /// `YYYY-MM`.
    pub month: String,
    pub created_at: String,
    pub updated_at: String,
}

/// A brand-new expense (id and timestamps are generated by the core).
#[derive(Debug, Clone)]
pub struct NewExpense {
    pub name: String,
    pub amount_cents: i64,
    pub kind: Kind,
    pub category: String,
    pub responsible: Responsible,
    pub joao_share: f64,
    pub joao_paid_cents: Option<i64>,
    pub anna_paid_cents: Option<i64>,
    pub due_date: Option<String>,
    pub paid: bool,
    pub notes: Option<String>,
    pub month: String,
}

/// Field patch for an existing expense — `None` = leave unchanged.
/// Nullable fields use `Option<Option<T>>` (`Some(None)` = clear).
#[derive(Debug, Clone, Default)]
pub struct ExpensePatch {
    pub name: Option<String>,
    pub amount_cents: Option<i64>,
    pub kind: Option<Kind>,
    pub responsible: Option<Responsible>,
    pub category: Option<String>,
    pub joao_share: Option<f64>,
    pub joao_paid_cents: Option<Option<i64>>,
    pub anna_paid_cents: Option<Option<i64>>,
    pub due_date: Option<Option<String>>,
    pub notes: Option<Option<String>>,
    pub paid: Option<bool>,
}

impl ExpensePatch {
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.name.is_none()
            && self.amount_cents.is_none()
            && self.kind.is_none()
            && self.responsible.is_none()
            && self.category.is_none()
            && self.joao_share.is_none()
            && self.joao_paid_cents.is_none()
            && self.anna_paid_cents.is_none()
            && self.due_date.is_none()
            && self.notes.is_none()
            && self.paid.is_none()
    }
}

